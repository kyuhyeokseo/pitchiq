"""Generate deterministic synthetic scenarios (public fixtures + private truth).

Examples:
    python -m app.simulator.generate --demo
    python -m app.simulator.generate --seed 42 --clips 150 --output data/generated/train_s42

Public output (served/consumed by the live system):
    <scenario_dir>/manifest.json
    <scenario_dir>/events.jsonl
    <scenario_dir>/tracking/<clip_id>.jsonl.gz
Private output (OFFLINE ONLY - evaluation/training labels):
    <truth_dir>/<scenario_id>.jsonl
"""

from __future__ import annotations

import argparse
import dataclasses
import gzip
import hashlib
import io
import json
import sys
import time
from collections import Counter
from pathlib import Path
from typing import Any

import numpy as np

from ..schemas import ScenarioManifest
from .engine import DT, A, D, simulate
from .export import ClipContext, canonical_player_id, export_events, export_frames
from .recipes import DEFAULT_RECIPES_PATH, REPO_ROOT, clip_streams, load_recipes, sample_clip_params
from .roster import TEAMS, roster

SCHEMA_VERSION = "1.0"
DATA_NOTICE = (
    "Synthetic data generated by PitchIQ. Fictional teams and players; "
    "not real football data and not validated against real matches."
)
TRACKING_NOTICE = (
    "Player and ball tracking (5 Hz) exists only inside the listed clip intervals; "
    "no tracking is available between clips."
)
DEFAULT_TRUTH_DIR = REPO_ROOT / "data" / "private_truth"
TEAM_ORDER = ("blue", "red")
# Canonical actor slots used in private truth records.
ACTOR_SLOTS = {
    "fullback": A("RB"), "winger": A("RW"), "carrier": A("RCM"),
    "defender_fullback": D("LB"), "defender_centreback": D("LCB"),
    "tracker": D("LW"), "cover_midfielder": D("LCM"),
}


def _dumps(obj: Any) -> str:
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False)


def _write_bytes(path: Path, data: bytes) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return hashlib.sha256(data).hexdigest()


def _gzip_bytes(raw: bytes) -> bytes:
    buf = io.BytesIO()
    # mtime=0 and empty filename make the archive byte-for-byte reproducible.
    with gzip.GzipFile(filename="", mode="wb", fileobj=buf, mtime=0, compresslevel=6) as gz:
        gz.write(raw)
    return buf.getvalue()


def period_of(start_match_s: float) -> int:
    return 1 if start_match_s < 2700.0 else 2


def attack_dir_for(team: str, period: int, blue_dir_p1: int) -> int:
    blue = blue_dir_p1 if period == 1 else -blue_dir_p1
    return blue if team == "blue" else -blue


def build_clip(cfg: dict, spec: dict, match_id: str, base_seed: int, clip_index: int,
               blue_dir_p1: int, response_override: str | None = None) -> tuple[list[dict], list[dict], dict]:
    attack_rng, defense_rng, motion_rng = clip_streams(base_seed, clip_index)
    params = sample_clip_params(cfg, spec["recipe"], attack_rng, defense_rng, response_override)
    res = simulate(params, motion_rng)
    period = period_of(spec["start_match_s"])
    attacking = spec["attacking_team"]
    ctx = ClipContext(
        match_id=match_id,
        clip_id=spec["clip_id"],
        start_match_s=float(spec["start_match_s"]),
        period=period,
        attacking_team=attacking,
        defending_team="red" if attacking == "blue" else "blue",
        flank=spec["flank"],
        attack_dir=attack_dir_for(attacking, period, blue_dir_p1),
    )
    frames = export_frames(res, ctx, TEAM_ORDER)
    events = export_events(res, ctx)
    markers: dict[str, Any] = {}
    for k, v in res.markers.items():
        if k == "final_receiver_index":
            markers["final_receiver_id"] = None if v is None else canonical_player_id(int(v), ctx)
        elif k.endswith("_t"):
            markers[k] = None if v is None else round(ctx.start_match_s + float(v), 3)
        else:
            markers[k] = v
    truth = {
        "scenario_id": spec.get("scenario_id"),
        "match_id": match_id,
        "clip_id": ctx.clip_id,
        "recipe_name": params.recipe_name,
        "pattern_truth": params.pattern_truth,
        "generator_intent": params.generator_intent,
        "defender_response": params.defender_response,
        "phase_truth": "central_circulation" if params.run_mode == "none" else "attacking_flank_buildup",
        "attacking_team_id": ctx.attacking_team,
        "flank_side": ctx.flank,
        "attack_direction": ctx.attack_direction,
        "base_seed": base_seed,
        "clip_index": clip_index,
        "actors": {name: canonical_player_id(i, ctx) for name, i in ACTOR_SLOTS.items()},
        "markers_match_s": markers,
        "params": dataclasses.asdict(params),
    }
    return frames, events, truth


def write_scenario(out_dir: Path, truth_path: Path, *, scenario_id: str, match_id: str, title: str,
                   generator_version: str, clips: list[tuple[list[dict], list[dict], dict]]) -> ScenarioManifest:
    out_dir.mkdir(parents=True, exist_ok=True)
    clip_infos = []
    all_events: list[dict] = []
    for frames, events, truth in clips:
        cid = frames[0]["clip_id"]
        raw = "".join(_dumps(f) + "\n" for f in frames).encode("utf-8")
        rel = f"tracking/{cid}.jsonl.gz"
        sha = _write_bytes(out_dir / rel, _gzip_bytes(raw))
        clip_infos.append(
            {
                "clip_id": cid,
                "period": frames[0]["period"],
                "start_match_s": frames[0]["match_time_s"],
                "end_match_s": frames[-1]["match_time_s"],
                "n_frames": len(frames),
                "sample_rate_hz": round(1.0 / DT, 6),
                "attack_direction": frames[0]["attack_direction"],
                "tracking_file": rel,
                "tracking_sha256": sha,
            }
        )
        all_events.extend(events)
    all_events.sort(key=lambda e: (e["match_time_s"], e["event_id"]))
    ev_sha = _write_bytes(out_dir / "events.jsonl", "".join(_dumps(e) + "\n" for e in all_events).encode("utf-8"))

    manifest = ScenarioManifest.model_validate(
        {
            "schema_version": SCHEMA_VERSION,
            "generator_version": generator_version,
            "scenario_id": scenario_id,
            "match_id": match_id,
            "title": title,
            "synthetic": True,
            "data_notice": DATA_NOTICE,
            "teams": [
                {"team_id": t.team_id, "name": t.name, "short_name": t.short_name, "color": t.color,
                 "nominal_formation": t.nominal_formation}
                for t in (TEAMS[k] for k in TEAM_ORDER)
            ],
            "roster": [r for k in TEAM_ORDER for r in roster(k)],
            "clips": sorted(clip_infos, key=lambda c: c["start_match_s"]),
            "events_file": "events.jsonl",
            "events_sha256": ev_sha,
            "tracking_available": TRACKING_NOTICE,
        }
    )
    (out_dir / "manifest.json").write_text(
        json.dumps(manifest.model_dump(mode="json"), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    truth_rows = [dict(t, scenario_id=scenario_id) for _, _, t in clips]
    _write_bytes(truth_path, "".join(_dumps(t) + "\n" for t in truth_rows).encode("utf-8"))
    return manifest


def generate_demo(cfg: dict, output: Path, truth_dir: Path) -> list[Path]:
    written = []
    for fx in cfg["demo_fixtures"]:
        clips = [
            build_clip(cfg, dict(spec, scenario_id=fx["scenario_id"]), fx["match_id"], fx["base_seed"], i,
                       fx["blue_attack_direction_period1"])
            for i, spec in enumerate(fx["clips"])
        ]
        out_dir = output / fx["scenario_id"]
        write_scenario(out_dir, truth_dir / f"{fx['scenario_id']}.jsonl", scenario_id=fx["scenario_id"],
                       match_id=fx["match_id"], title=fx["title"], generator_version=cfg["generator_version"],
                       clips=clips)
        written.append(out_dir)
    return written


def plan_dataset(cfg: dict, seed: int, n_clips: int, recipes: list[str] | None) -> tuple[list[dict], int]:
    mix = {k: v for k, v in cfg["dataset_mix"].items() if recipes is None or k in recipes}
    if not mix:
        raise SystemExit(f"no recipes selected from {sorted(cfg['dataset_mix'])}")
    names = sorted(mix)
    w = np.array([mix[n] for n in names], dtype=float)
    rng = np.random.default_rng(np.random.SeedSequence([int(seed), 2**31 - 1]))
    blue_dir_p1 = int(rng.choice([1, -1]))
    per_period = Counter()
    specs = []
    for i in range(n_clips):
        period = int(rng.integers(1, 3))
        slot = per_period[period]
        per_period[period] += 1
        specs.append(
            {
                "clip_id": f"k{i:04d}",
                "recipe": names[int(rng.choice(len(names), p=w / w.sum()))],
                "attacking_team": str(rng.choice(TEAM_ORDER)),
                "flank": str(rng.choice(["right", "left"])),
                "start_match_s": round((0.0 if period == 1 else 2700.0) + 10.0 + 26.0 * slot, 1),
            }
        )
    return specs, blue_dir_p1


def generate_dataset(cfg: dict, seed: int, n_clips: int, output: Path, truth_dir: Path,
                     recipes: list[str] | None = None) -> Path:
    scenario_id = output.name
    match_id = f"synthetic_{scenario_id}"
    specs, blue_dir_p1 = plan_dataset(cfg, seed, n_clips, recipes)
    clips = [
        build_clip(cfg, dict(spec, scenario_id=scenario_id), match_id, seed, i, blue_dir_p1)
        for i, spec in enumerate(specs)
    ]
    write_scenario(output, truth_dir / f"{scenario_id}.jsonl", scenario_id=scenario_id, match_id=match_id,
                   title=f"Synthetic clip collection {scenario_id}", generator_version=cfg["generator_version"],
                   clips=clips)
    return output


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--demo", action="store_true", help="build the curated demo fixtures")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--clips", type=int, default=24)
    ap.add_argument("--output", type=Path, default=None)
    ap.add_argument("--truth-dir", type=Path, default=DEFAULT_TRUTH_DIR)
    ap.add_argument("--recipes", type=str, default=None, help="comma-separated subset of dataset_mix")
    ap.add_argument("--config", type=Path, default=DEFAULT_RECIPES_PATH)
    ap.add_argument("--no-validate", action="store_true")
    args = ap.parse_args(argv)

    from .validate import validate_scenario_dir

    cfg = load_recipes(args.config)
    t0 = time.perf_counter()
    if args.demo:
        dirs = generate_demo(cfg, args.output or REPO_ROOT / "data" / "fixtures", args.truth_dir)
    else:
        if args.output is None:
            ap.error("--output is required for dataset generation")
        recipes = args.recipes.split(",") if args.recipes else None
        dirs = [generate_dataset(cfg, args.seed, args.clips, args.output, args.truth_dir, recipes)]
    gen_s = time.perf_counter() - t0

    ok = True
    for d in dirs:
        man = json.loads((d / "manifest.json").read_text())
        n_frames = sum(c["n_frames"] for c in man["clips"])
        print(f"[generate] {d}: clips={len(man['clips'])} frames={n_frames} events_sha256={man['events_sha256'][:12]}")
        truth = [json.loads(l) for l in (args.truth_dir / f"{man['scenario_id']}.jsonl").read_text().splitlines()]
        print(f"[generate]   private recipe counts (dev console only): {dict(Counter(t['recipe_name'] for t in truth))}")
        if not args.no_validate:
            report = validate_scenario_dir(d, truth_path=args.truth_dir / f"{man['scenario_id']}.jsonl",
                                           private_vocab_cfg=cfg)
            print(f"[validate]   {report.summary()}")
            for err in report.errors[:20]:
                print(f"[validate]   ERROR {err}")
            ok = ok and report.ok
    print(f"[generate] wall time {gen_s:.2f}s")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
