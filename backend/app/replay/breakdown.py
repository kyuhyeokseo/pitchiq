"""The guided breakdown of one defensive moment, in four steps a fan can follow: the press (who closes down the player
on the ball, who follows whom), what it takes away, what it leaves open, and what happened next. Each step points at
the revision where the analysis first had it, so the pitch shows the moment as it was known then; what the press takes
away and what it leaves open share one moment (the first that has the cost) when the restriction still holds there.

Everything comes from the evidence the replay has so far: the sentences are the deterministic fan sentences rendered
by code (every number from the packet), the players, marking pairs and drawing layers come from the claims and
relations, and the ball's path comes from the frames between the outcome's pass and its reception. When the analysis
recorded no outcome, the last step shows the next pass (or shot) the replay has seen (who played it, and who received,
intercepted or stopped it) as an observation, without saying whether it used what was left open, or that the clip
ends first. A press step without a sentence about the press shows who has the ball and the nearest defender, measured
on its frame. Nothing here is generated by a
model, and a step that the analysis has not reached yet says so instead of guessing.
"""

from __future__ import annotations

from ..agents.fallback import analyst_plan, producer_plan
from ..contracts import EvidencePacket
from ..narrative.render import render_sentence
from ..overlay.builder import key_state
from .catalog import Clip

# the drawing layers that show each claim (overlay builder layers)
CLAIM_LAYERS = {
    "short_options_screened": ("screened_lanes", "pressure"),
    "central_routes_screened": ("screened_lanes", "pressure"),
    "behind_depth_reduced": ("structure",),
    "press_block_disconnected": ("structure", "pressure"),
    "behind_space_exposed": ("exposure", "cover", "structure"),
    "isolated_1v1": ("exposure", "cover"),
    "between_lines_receiver": ("outlets", "structure"),
    "wide_outlet_available": ("outlets",),
    "accessible_free_receiver": ("outlets", "exposure"),
    "local_central_overload": ("numbers",),
}
PRESS_TEMPLATES = ("press_cut", "passive_screen", "press_numbers")
OBSERVED = ("exploited_in_synthetic_play", "not_exploited_in_window")
ALIGN_S = 1.0  # the press is told on the moment of the cost when that comes more than this much later
# unmarked players (the same rule as the pitch's rings): no opponent within UNMARKED_M, not followed by a marker, within
# UNMARKED_REACH_M of the ball (a switch to the far side counts); the UNMARKED_MAX with the most room
UNMARKED_M, UNMARKED_REACH_M, UNMARKED_MAX = 10.0, 60.0, 3


def _sentences(pk: EvidencePacket, language: str, clip: Clip, audience: str = "fan") -> list[tuple[str, str | None, str]]:
    """(template key, claim id, rendered text) of the deterministic fan (or analyst) plan for this revision."""
    plan = producer_plan(pk, analyst_plan(pk)).variant(audience, language)
    return [(s.template_key, s.claim_id, render_sentence(s, pk, language, clip.meta)) for s in plan.sentences]


def _holds_restriction(pk: EvidencePacket) -> bool:
    """A restricted claim of this revision is still supported at its analysis cutoff (not only earlier on)."""
    until = key_state(pk).analyzed_until_s
    return any(c.window.end_s >= until - 0.25 for c in pk.claims if c.claim_id in pk.episode.restricted_claim_ids)


def _press_step_out(pk: EvidencePacket, language: str, clip: Clip, presser: str | None) -> list[str]:
    """The fan sentence of an observed step by the presser himself (a defender who left the screen to close the ball
    down): that step is the press, so the press step tells it."""
    acts = {c.change_id for c in pk.changes if c.code == "defender_step" and presser and c.actor_player_ids[:1] == [presser]}
    if not acts:
        return []
    plan = producer_plan(pk, analyst_plan(pk)).variant("fan", language)
    return [render_sentence(s, pk, language, clip.meta) for s in plan.sentences if s.change_id in acts]


def _layers(codes) -> list[str]:
    out: list[str] = []
    for code in codes:
        for layer in CLAIM_LAYERS.get(code, ()):
            if layer not in out:
                out.append(layer)
    return out


def _step(key: str, pk: EvidencePacket, layers, players, sentences, roles=None, **extra) -> dict:
    """roles: the players a fan should look at first, by what they do in this step (presser, carrier, runner, cover,
    passer, receiver), from the relations and events."""
    roles = {p: r for p, r in (roles or {}).items() if p}
    return {"key": key, "revision": pk.episode.revision, "match_time_s": key_state(pk).analyzed_until_s,
            "layers": list(layers), "player_ids": sorted(set(players) | set(roles)), "roles": roles,
            "sentences": sentences, **extra}


def _other_runs(pk: EvidencePacket, roles: dict[str, str]) -> list[dict]:
    """Other runs in behind on the same frame (the cover relations the analysis timed), beside the claim's runner:
    the runner, the defender going with him, and whether that cover is in time."""
    out = []
    for cv in key_state(pk).covers:
        if cv.relation_id.split("_")[-2] != "out" or roles.get(cv.attacker_id) == "runner":
            continue
        if all(o["runner_id"] != cv.attacker_id for o in out):
            out.append({"runner_id": cv.attacker_id, "cover_id": cv.cover_player_id, "in_time": cv.status == "ok"})
    return out


def _runner_and_cover(pk: EvidencePacket, exposed) -> dict[str, str]:
    """The runner the exposed claims measure, and the defender whose cover the analysis timed for that run."""
    runner = next((pk.metric(m).player_ids[0] for c in exposed for m in c.metric_ids
                   if pk.metric(m).key == "runner_forward_speed_mps" and pk.metric(m).player_ids), None)
    if runner is None:
        return {}
    # the outgoing cover the overlay draws for that runner
    cov = next((cv for cv in key_state(pk).covers if cv.attacker_id == runner and cv.status == "ok"
                and cv.cover_player_id and cv.relation_id.split("_")[-2] == "out"), None)
    return {runner: "runner", **({cov.cover_player_id: "cover"} if cov else {})}


def _path(clip: Clip, start_s: float, end_s: float) -> list[list[float]]:
    """The ball between two event times, from the frames (world metres)."""
    return [[round(f.ball.position.x_m, 2), round(f.ball.position.y_m, 2)] for f in clip.frames
            if start_s - 1e-6 <= f.match_time_s <= end_s + 1e-6]


def _ball_path(clip: Clip, event_ids: list[str]) -> tuple[list[list[float]], list[str]]:
    """The ball from the outcome's pass to its reception, from the frames (world metres), and who passed and received."""
    events = {e.event_id: e for e in clip.events}
    evs = sorted((events[i] for i in event_ids if i in events), key=lambda e: e.event_time_s)
    release = next((e for e in evs if e.kind == "pass_release"), None)
    receive = next((e for e in evs if e.kind == "pass_receive"), None)
    if release is None or receive is None:
        return [], []
    players = [p for p in (release.actor_id, receive.target_id) if p]
    return _path(clip, release.event_time_s, receive.event_time_s), players


def _next_on_ball(clip: Clip, after_s: float, until_s: float, now_s: float) -> dict | None:
    """The first pass (or shot) played after the moment was detected (up to until_s), once the replay has seen where it
    ended: received by a team-mate, intercepted, or for a shot stopped. An observation only; whether it used what was
    left open is the outcome's call, which the analysis makes in its own revisions."""
    starts = sorted((e for e in clip.events if e.kind in ("pass_release", "shot")
                     and after_s - 1e-6 <= e.event_time_s <= until_s + 1e-6), key=lambda e: e.event_time_s)
    if not starts or starts[0].available_at_s > now_s + 1e-9 or starts[0].actor_id is None:
        return None
    start = starts[0]
    end = next((e for e in clip.events if e.related_event_id == start.event_id
                and e.kind in ("pass_receive", "interception") and e.available_at_s <= now_s + 1e-9), None)
    if end is None:
        return None
    to = end.target_id if end.kind == "pass_receive" else end.actor_id
    if to is None:
        return None
    kind = "pass" if end.kind == "pass_receive" else "interception"
    if start.kind == "shot":  # a keeper's stop is a save, anyone else's a block
        keeper = next((p.is_goalkeeper for p in clip.frames[clip.frame_at(end.event_time_s)].players if p.player_id == to),
                      False)
        kind = "save" if keeper else "block"
    return {"kind": kind, "from_id": start.actor_id, "to_id": to, "release_s": start.event_time_s,
            "end_s": end.event_time_s, "path": _path(clip, start.event_time_s, end.event_time_s)}


def _movers(pk: EvidencePacket) -> list[str]:
    """The players the observed changes name ("RED #7 stepped up ...", "BLU #2 moved ...")."""
    return [p for ch in pk.changes for p in ch.actor_player_ids]


def _press_facts(clip: Clip, pk: EvidencePacket) -> dict | None:
    """Who has the ball on the step's frame and the nearest defender to him, from the frame's positions (for a moment
    whose narration has no sentence about the press)."""
    state = key_state(pk)
    frame = clip.frames[min(state.frame_ref.frame_index, len(clip.frames) - 1)]
    carrier = frame.ball.owner_id or (state.pressures[0].carrier_id if state.pressures else None)
    at = {p.player_id: p.position for p in frame.players}
    if carrier not in at:
        return None
    c = at[carrier]
    near = min(((((q.x_m - c.x_m) ** 2 + (q.y_m - c.y_m) ** 2) ** 0.5, p.player_id) for p in frame.players
                if p.team_id == pk.episode.defending_team_id for q in (p.position,)), default=None)
    if near is None:
        return None
    return {"carrier_id": carrier, "defender_id": near[1], "distance_m": round(near[0], 1)}


def _unmarked(clip: Clip, pk: EvidencePacket, first: tuple[str, ...] = ()) -> list[str]:
    """The attacking team's unmarked outfield players on the step's frame: what a shape leaves free whether or not a
    pass to them is on (an observation from positions; the claims say what is reachable). A player in an offside
    position is not counted; players in ``first`` (the free receivers the claims name) come first when unmarked."""
    state = key_state(pk)
    frame = clip.frames[min(state.frame_ref.frame_index, len(clip.frames) - 1)]
    defending = pk.episode.defending_team_id
    followed = {mk.attacker_id for mk in state.markings if mk.status == "ok"}
    b = frame.ball.position
    dist = lambda p, q: ((p.x_m - q.x_m) ** 2 + (p.y_m - q.y_m) ** 2) ** 0.5  # noqa: E731
    opp = [p.position for p in frame.players if p.team_id == defending]
    room = lambda p: min(dist(p.position, q) for q in opp)  # noqa: E731
    attacking = next((p.team_id for p in frame.players if p.team_id != defending), None)
    a = clip.meta.attack_direction(attacking) if attacking else 1
    fwd = lambda x: x if a == 1 else 105.0 - x  # noqa: E731
    # the offside line: the second-last defender (keeper included), or the ball if it is further forward
    line = max(sorted((fwd(p.position.x_m) for p in frame.players if p.team_id == defending), reverse=True)[1:2]
               + [fwd(b.x_m)])
    out = [(p.player_id not in first, -room(p), p.player_id) for p in frame.players
           if p.team_id != defending and not p.is_goalkeeper and p.player_id != frame.ball.owner_id
           and p.player_id not in followed and dist(p.position, b) <= UNMARKED_REACH_M and room(p) >= UNMARKED_M
           and fwd(p.position.x_m) <= line + 0.5]
    return [pid for *_, pid in sorted(out)[:UNMARKED_MAX]]


def breakdown(revs: list[EvidencePacket], clip: Clip, language: str, now_s: float | None = None,
              next_window_s: float = 0.0) -> dict:
    """now_s: the replay clock (events the replay has seen); next_window_s: how long after the analysis of the moment
    ended a pass still counts as its next pass (the outcome window)."""
    latest = revs[-1]
    restricting = [p for p in revs if p.episode.restricted_claim_ids] or revs[:1]
    # the first revision that can tell the press in words, else the first that restricts anything
    r_press = next((p for p in restricting
                    if any(any(m in k for m in PRESS_TEMPLATES) for k, _, _ in _sentences(p, language, clip))),
                   restricting[0])
    r_out = next((p for p in revs if p.episode.outcome.status in OBSERVED), None)
    # what it leaves open: once the attack has used the defence's weakness, the claim about the player who received the
    # ball (so steps 3 and 4 tell the same story), else the first exposed claims
    target = r_out.episode.outcome.realized_target_id if r_out is not None else None
    about_target = lambda p: [c for c in p.claims  # noqa: E731
                              if c.claim_id in p.episode.exposed_claim_ids and target in c.player_ids]
    r_open = (next((p for p in revs if target and about_target(p)), None)
              or next((p for p in revs if p.episode.exposed_claim_ids), None))
    # what it takes away and what it leaves open are one picture: when the cost appears later than the press was
    # first told, and the analysis still has the restriction at that moment, steps 1-3 all show that moment
    if r_open is not None and _holds_restriction(r_open) and (
            key_state(r_open).analyzed_until_s - key_state(r_press).analyzed_until_s > ALIGN_S):
        r_press = r_open
    # nothing open, but a reason held back (a run covered in time, a runner offside): that is the moment it is about
    held = [dict(zip(("code", "reason", "player_id"), f.split(":")[:3]))
            for f in latest.forbidden_inferences if f.count(":") >= 2]
    if r_open is None and held and _holds_restriction(latest) and (
            key_state(latest).analyzed_until_s - key_state(r_press).analyzed_until_s > ALIGN_S):
        r_press = latest
    steps = []

    # 1. the press: who closes down the player on the ball, and who follows whom
    sents = _sentences(r_press, language, clip)
    state = key_state(r_press)
    roles = {k: v for pr in state.pressures[:1] for k, v in ((pr.presser_id, "presser"), (pr.carrier_id, "carrier"))}
    press_lines = (_press_step_out(r_press, language, clip, state.pressures[0].presser_id if state.pressures else None)
                   + [t for k, _, t in sents if any(m in k for m in PRESS_TEMPLATES)])
    facts = _press_facts(clip, r_press)
    if facts and not roles:  # nobody presses: the player on the ball is still the one to look at
        roles = {facts["carrier_id"]: "carrier"}
    # who follows whom: the sustained marking relations on the same frozen state (defender, attacker)
    marks = [[mk.defender_id, mk.attacker_id] for mk in state.markings if mk.status == "ok"]
    # the nearest defender is named by the facts and by "nobody closes him down (nearest defender ...)"
    steps.append(_step("press", r_press, ("pressure",), [facts["defender_id"]] if facts else (), press_lines, roles,
                       marks=marks, press_facts=None if press_lines else facts))
    # the passes step 2 draws as blocked (carrier, receiver): a pass in step 4 along one of them is pointed out
    blocked = {(ln.carrier_id, ln.receiver_id) for ln in state.lanes if ln.availability == "screened"}

    # 2. what it takes away
    restricted = [c for c in r_press.claims if c.claim_id in r_press.episode.restricted_claim_ids]
    steps.append(_step("takes_away", r_press, _layers(c.code for c in restricted),
                       [p for c in restricted for p in c.player_ids],
                       [t for k, cid, t in sents if cid in r_press.episode.restricted_claim_ids
                        and not any(m in k for m in PRESS_TEMPLATES)]))

    # 3. what it leaves open (or that nothing open is supported yet)
    if r_open is not None:
        exposed = about_target(r_open) if target else []
        exposed = exposed or [c for c in r_open.claims if c.claim_id in r_open.episode.exposed_claim_ids]
        ids = {c.claim_id for c in exposed}
        # the fan plan keeps a few sentences; when none is about these claims, the analyst plan says it
        texts = ([t for _, cid, t in _sentences(r_open, language, clip) if cid in ids]
                 or [t for _, cid, t in _sentences(r_open, language, clip, "analyst") if cid in ids])
        roles = _runner_and_cover(r_open, exposed)
        others = _other_runs(r_open, roles) if "runner" in roles.values() else []
        named = {p for c in exposed for p in c.player_ids}
        free = tuple(p for c in exposed if c.code in ("accessible_free_receiver", "between_lines_receiver",
                                                       "wide_outlet_available") for p in c.player_ids)
        steps.append(_step("leaves_open", r_open, _layers(c.code for c in exposed), sorted(named), texts,
                           {**{o["runner_id"]: "runner" for o in others}, **roles},
                           unmarked=_unmarked(clip, r_open, free), other_runs=others))
    else:
        # nothing open is supported: say so, and why a claim was held back when the analysis recorded a reason
        # (code:reason:player, such as a run from an offside position)
        # the moment itself (a reason held back later, about a run, is still listed)
        at = r_press
        steps.append(_step("leaves_open", at, (), [h["player_id"] for h in held if "_" in h["player_id"]],
                           [t for k, _, t in _sentences(at, language, clip) if k.startswith("partial.")],
                           held_back=held, unmarked=_unmarked(clip, at)))

    # 4. what happened next, once the replay has seen it
    if r_out is not None:
        path, movers = _ball_path(clip, r_out.episode.outcome.event_ids)
        exposed_codes = [c.code for c in r_out.claims if c.claim_id in r_out.episode.exposed_claim_ids]
        steps.append(_step("what_happened", r_out, _layers(exposed_codes) + ["changes"], _movers(r_out),
                           [t for k, _, t in _sentences(r_out, language, clip)
                            if k.startswith(("change.", "outcome.")) and t not in press_lines],
                           dict(zip(movers, ("passer", "receiver"))), ball_path=path,
                           through_blocked=tuple(movers) in blocked))
    else:
        # no pass into the space: what the play has shown (observed adjustments), the outcome's state, and the next pass
        # once the replay has seen it, which stands in for "not observed yet"
        nxt = None if now_s is None else _next_on_ball(clip, latest.episode.detected_at_s,
                                                       key_state(latest).analyzed_until_s + next_window_s, now_s)
        # the replay reached the end of the clip and nobody played the ball on after the moment
        clip_ends = (nxt is None and now_s is not None and now_s >= clip.end_s - 1e-6
                     and not any(e.kind in ("pass_release", "shot") and e.event_time_s >= latest.episode.detected_at_s - 1e-6
                                 for e in clip.events))
        # what the replay saw (the next pass, or the clip ending first) replaces "not observed yet"; the clip ending
        # first also stands in for "nothing was used"
        drop = ({"outcome.pending"} if nxt else set()) | ({"outcome.pending", "outcome.inconclusive"} if clip_ends else set())
        sents = [t for k, _, t in _sentences(latest, language, clip)
                 if k.startswith(("change.", "outcome.")) and k not in drop and t not in press_lines]
        shot = nxt is not None and nxt["kind"] in ("save", "block")
        roles = {} if nxt is None else {nxt["from_id"]: "shooter" if shot else "passer",
                                        nxt["to_id"]: {"pass": "receiver", "interception": "interceptor",
                                                       "save": "saver", "block": "blocker"}[nxt["kind"]]}
        steps.append(_step("what_happened", latest, ("changes",) if latest.changes else (), _movers(latest), sents,
                           roles, ball_path=nxt.pop("path") if nxt else [], next_pass=nxt, clip_ends=clip_ends,
                           through_blocked=nxt is not None and nxt["kind"] == "pass"
                           and (nxt["from_id"], nxt["to_id"]) in blocked))
    return {"episode_id": latest.episode.episode_id, "analysis_status": latest.episode.analysis_status,
            "outcome": latest.episode.outcome.status, "language": language, "steps": steps}
